export function normalizeLanguage(value) {
  if (typeof value !== 'string') return 'en';
  const language = value.trim().toLowerCase().replaceAll('_', '-');
  if (language === 'es' || language === 'es-es') return 'es';
  if (language === 'gl' || language === 'gl-es') return 'gl';
  return 'en';
}

/** Interpolation is plain text; each rendering context remains responsible for escaping. */
export function translate(language, key, params = {}) {
  const dictionary = messages[normalizeLanguage(language)];
  if (!Object.hasOwn(dictionary, key)) throw new RangeError('Unknown translation key: ' + key);
  return dictionary[key].replace(/\{([a-zA-Z][a-zA-Z\d_]*)\}/g, (_, name) => {
    if (!Object.hasOwn(params, name) || params[name] == null) throw new TypeError('Missing translation parameter: ' + name);
    return String(params[name]);
  });
}
